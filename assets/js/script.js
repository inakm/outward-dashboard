  async function loadRoutePlan() {
    var data = null;
    if (window.ROUTE_PLAN && window.ROUTE_PLAN.records) {
      data = window.ROUTE_PLAN;
    } else {
      try {
        var res = await fetch(ROUTE_PLAN_URL);
        if (!res.ok) throw new Error('HTTP ' + res.status);
        data = await res.json();
      } catch (e) {
        console.warn('R1-R7 route plan unavailable (' + ROUTE_PLAN_URL + '):', e);
      }
    }
    if (!data || !data.records) return;
    routePlanData = data;
    if (!routeMap) routeMap = {};
    if (!routeMapCircle) routeMapCircle = {};
    var added = 0;
    data.records.forEach(function (rec) {
      var slug = routeNameSlug(rec.name);
      if (!slug) return;
      if (!routeMap[slug]) {
        routeMap[slug] = rec.route;
        added++;
      }
      if (!routeMapCircle[slug]) {
        routeMapCircle[slug] = { route: rec.route, circle: rec.circle || rec.name, note: rec.note || rec.zone || '' };
      }
      if (rec.lat != null && rec.lng != null && !(rec.name in coordsIndex)) {
        coordsIndex[rec.name] = { lat: Number(rec.lat), lng: Number(rec.lng) };
      }
      if (!(rec.route in routeNames) && ROUTE_DESCRIPTIONS[rec.route]) {
        routeNames[rec.route] = ROUTE_DESCRIPTIONS[rec.route];
      }
    });
    var hadRoute = 0;
    for (var i = 0; i < state.records.length; i++) if (state.records[i].route) hadRoute++;
    enrichRoutes(state.records, routeMap);
    enrichRoutesFromMaster(state.records);
    renderAll();
    var withRoute = 0;
    for (var j = 0; j < state.records.length; j++) if (state.records[j].route) withRoute++;
    if (withRoute > hadRoute) {
      toast('Auto-routed ' + (withRoute - hadRoute) + ' orders from Branch (R1-R7 plan)', 'info');
    }
  }

