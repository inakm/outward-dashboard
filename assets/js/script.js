  async function syncFromSheet() {
    if (syncing) return;
    syncing = true;
    setSyncing(true);
    try {
      var records;
      var via = 'csv';
      try {
        var res = await fetch(SHEET_CSV_URL);
        if (!res.ok) throw new Error('HTTP ' + res.status);
        var csv = await res.text();
        var wb = XLSX.read(csv, { type: 'string' });
        var result = ingestWorkbook(wb);
        if (result.missing.length) throw new Error('Sheet columns not recognised: ' + result.missing.join(', '));
        if (!result.records.length) throw new Error('Sheet contains no data rows.');
        records = result.records;
      } catch (csvErr) {
        via = 'gviz';
        var gRes = await fetch(SHEET_GVIZ_URL);
        if (!gRes.ok) throw new Error('HTTP ' + gRes.status);
        var raw = parseGvizRows(await gRes.text());
        records = raw.map(normalizeRecord);
      }
      if (!records.length) throw new Error('Sheet contains no usable rows.');
      applyRecords(records, { name: 'Live Google Sheet', syncedAt: Date.now(), via: via });
      toast('Synced ' + formatNum(records.length) + ' rows from Google Sheet', 'success');
      try {
        await syncCustomersFromSheet();
      } catch (custErr) {
        if (isFileProtocol()) showLocalNotice();
        console.warn('Location pull sync failed:', custErr);
        toast('Customer master sync failed — ' + describeSyncError(custErr), 'error');
      }
    } catch (err) {
      if (isFileProtocol()) showLocalNotice();
      showError('Google Sheet sync failed — ' + describeSyncError(err));
    } finally {
      setSyncing(false);
      syncing = false;
    }
  }

  /* Pull the customer master from the 'Location pull' sheet in the same
     Google Sheet. Primary Zone (col I) drives R1–R7 routing for orders whose
     branch didn't match the route plan. */
  async function syncCustomersFromSheet() {
    var url = SHEET_GVIZ_URL + '&sheet=' + encodeURIComponent(SHEET_LOCATION_SHEET);
    var res = await fetch(url);
    if (!res.ok) throw new Error('HTTP ' + res.status);
    var grid = parseGvizGrid(await res.text());
    if (classifyWorkbook(grid) !== 'customers') {
      throw new Error('Location pull sheet columns not recognised (expected Code, Name, …, Primary Zone).');
    }
    var custs = parseCustomerMaster(grid);
    if (!custs.length) throw new Error('Location pull sheet contains no customer rows.');
    applyCustomers(custs, { name: 'Google Sheet · ' + SHEET_LOCATION_SHEET, syncedAt: Date.now(), via: 'gviz' });
    toast('Synced ' + formatNum(custs.length) + ' customers from Google Sheet (' + SHEET_LOCATION_SHEET + ')', 'success');
  }

