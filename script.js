  async function loadRouteMap() {
    var data = null;
    if (window.GHMC_ROUTE_MAP && window.GHMC_ROUTE_MAP.records) {
      data = window.GHMC_ROUTE_MAP;
    } else {
      try {
        var res = await fetch(GHMC_MAP_URL);
        if (!res.ok) throw new Error('HTTP ' + res.status);
        data = await res.json();
      } catch (e) {
        console.warn('GHMC route map unavailable (' + GHMC_MAP_URL + '):', e);
      }
    }
    if (!data || !data.records) return;
    routeMap = buildRouteIndex(data.records);
    routeMapCircle = buildCircleIndex(data.records);
    coordsIndex = {};
    routeNames = {};
    data.records.forEach(function (rec) {
      var circle = rec['GHMC Circle Name'];
      if (circle) {
        if (rec['Circle Lat'] != null && rec['Circle Lng'] != null && !(circle in coordsIndex)) {
          coordsIndex[circle] = { lat: Number(rec['Circle Lat']), lng: Number(rec['Circle Lng']) };
        }
        if (!(rec['Route Code'] in routeNames)) routeNames[rec['Route Code']] = rec['Route Name'];
      }
    });
    var hadRoute = 0;
    for (var i = 0; i < state.records.length; i++) if (state.records[i].route) hadRoute++;
    enrichRoutes(state.records, routeMap);
    renderAll();
    var withRoute = 0;
    for (var j = 0; j < state.records.length; j++) if (state.records[j].route) withRoute++;
    if (withRoute > hadRoute) {
      toast('Auto-routed ' + (withRoute - hadRoute) + ' orders from Branch (GHMC map)', 'info');
    }
  }

